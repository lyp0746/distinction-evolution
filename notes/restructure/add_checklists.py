def box(a, b, c, d, e):
    return (f'<div class="note"><b>本章清单</b>\n<ul>\n'
            f'<li><b>⊗ 可引用（A）：</b>{a}</li>\n'
            f'<li><b>⊕ 有论证（B）：</b>{b}</li>\n'
            f'<li><b>○ 启发／描述（C）：</b>{c}</li>\n'
            f'<li><b>？ 未解决：</b>{d}</li>\n'
            f'<li><b>↔ 连接：</b>{e}</li>\n'
            f'</ul></div>')

def main():
    for fn, parts in BOXES.items():
        p = os.path.join(SRC, fn)
        t = open(p, encoding="utf-8").read()
        if "本章清单" in t:
            print("already has checklist:", fn); continue
        marker = "<h3>本章参考文献</h3>"
        if marker not in t:
            print("no refs marker:", fn); continue
        t = t.replace(marker, box(*parts) + "\n\n" + marker, 1)
        open(p, "w", encoding="utf-8").write(t)
        print("added checklist:", fn)

if __name__ == "__main__":
    main()
