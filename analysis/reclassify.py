# -*- coding: utf-8 -*-
"""reclassify.py — 从六元组重导分类：把"X 的度量"与"𝒟 的代数"分开

现行三轴的问题（第 23.5.1—23.5.2 节已指出）：
  轴 1 把两件不同的事混在一起——(i) 对象集 X 的量级（有限/可数/稠密/无限自由）；
  (ii) 区分动作族 𝒟 的代数闭包（线性/格/拓扑/度量/逻辑）。
  后果："拓扑×正×连续"被列为空缺，其实 C4/C5/P4 是 (X 有限, 𝒟 格) 的实例。

本脚本按六元组结构重导五个坐标：
  A = X 的量级           {0有限, 1可数, 2稠密, 3无限自由}
  B = 𝒟 的代数闭包        {线性, 格, 拓扑, 度量, 逻辑}
  C = O 的分辨率          {稀疏, 中, 精细, 完全}
  D = κ 符号             {负, 零, 正}
  E = 演化型             {无, 离散可逆, 离散不可逆, 连续可积, 连续耗散}

按 A 分层（嵌套树），而不是全局笛卡尔积；A=3 直接标为 O16 禁区。

诚实边界：坐标为作者判断（C／丙）；这是分类设计，不是定理。
输出：analysis/results/reclassify.json。
"""
import itertools
import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(HERE, "analysis", "results")

# (领域, A, B集合, C, D集合, E)
D = [
    ("图论", 0, ["格", "线性"], "精细", ["负", "零", "正"], "连续耗散"),
    ("线性代数", 2, ["线性"], "中", ["零"], "无"),
    ("表示论", 1, ["线性"], "中", ["零"], "无"),
    ("调和分析", 2, ["线性"], "中", ["零"], "连续耗散"),
    ("点集拓扑", 2, ["拓扑", "格"], "精细", ["负"], "无"),
    ("代数拓扑", 1, ["线性", "拓扑"], "稀疏", ["负"], "无"),
    ("测度论", 2, ["度量"], "中", ["正"], "无"),
    ("实分析", 2, ["度量"], "中", ["正"], "无"),
    ("泛函分析", 2, ["线性", "度量"], "中", ["正"], "无"),
    ("复分析", 2, ["度量", "拓扑"], "精细", ["零"], "无"),
    ("组合数学", 0, ["格", "逻辑"], "精细", ["正"], "无"),
    ("数论", 1, ["格", "逻辑"], "中", ["正"], "无"),
    ("数理逻辑", 1, ["逻辑"], "精细", ["零"], "无"),
    ("类型论", 1, ["逻辑", "拓扑"], "精细", ["负"], "无"),
    ("微分方程", 2, ["度量", "线性"], "中", ["负", "零", "正"], "连续耗散"),
    ("动力系统", 2, ["度量", "格"], "中", ["负", "零", "正"], "离散不可逆"),
    ("概率论", 2, ["度量"], "中", ["负", "零", "正"], "无"),
    ("信息论", 0, ["度量", "逻辑"], "中", ["负"], "无"),
    ("算子代数", 2, ["线性", "拓扑"], "稀疏", ["负", "零", "正"], "连续可积"),
    ("量子数学", 2, ["线性"], "稀疏", ["正"], "连续可积"),
    ("博弈论", 0, ["格", "逻辑"], "中", ["负", "零", "正"], "离散不可逆"),
    ("优化", 2, ["度量", "线性"], "中", ["负", "零", "正"], "连续耗散"),
    ("数值分析", 0, ["线性", "度量"], "中", ["正"], "离散不可逆"),
    ("微分几何", 2, ["度量", "拓扑", "线性"], "精细", ["负", "零", "正"], "连续耗散"),
    ("LLM 潜在空间", 2, ["线性", "度量"], "稀疏", ["正"], "离散不可逆"),
    ("马尔可夫链", 0, ["格", "度量"], "中", ["负", "零", "正"], "离散不可逆"),
    ("编码论", 0, ["逻辑", "格"], "精细", ["正"], "无"),
    ("生成拓扑", 3, ["拓扑"], "完全", ["正"], "无"),   # A=3 无限自由
]

A_LABEL = {0: "0 有限", 1: "1 可数", 2: "2 稠密", 3: "3 无限自由"}
B_ALL = ["线性", "格", "拓扑", "度量", "逻辑"]
D_ALL = ["负", "零", "正"]
E_ALL = ["无", "离散可逆", "离散不可逆", "连续可积", "连续耗散"]


def main():
    layers = {}
    for a in range(4):
        doms = [d for d in D if d[1] == a]
        cells = set()
        for name, aa, bs, c, ds, e in doms:
            for b, dd in itertools.product(bs, ds):
                cells.add((b, dd, e))
        total = len(B_ALL) * len(D_ALL) * len(E_ALL)   # 5*3*5 = 75
        layers[a] = {
            "label": A_LABEL[a],
            "domains": [d[0] for d in doms],
            "occupied": len(cells),
            "empty": total - len(cells),
            "total": total,
            "note": ("O16 禁区（无限自由 -> 无有限描述，EDS 不适用）" if a == 3 else ""),
            "occupied_cells": sorted(f"{b}/{d}/{e}" for b, d, e in cells),
        }
    out = {"coordinate_axes": {"A": A_LABEL, "B": B_ALL, "C": "稀疏/中/精细/完全",
                               "D": D_ALL, "E": E_ALL},
           "layers": layers,
           "caveat": "坐标为作者判断（C／丙）；这是分类设计，不是定理。"}
    os.makedirs(RES, exist_ok=True)
    with open(os.path.join(RES, "reclassify.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    for a in range(4):
        L = layers[a]
        print(f"{L['label']}: 领域 {len(L['domains'])}，占据 {L['occupied']}/{L['total']}，"
              f"空缺 {L['empty']} {L['note']}")
    print("[done]", os.path.join(RES, "reclassify.json"))


if __name__ == "__main__":
    main()
